import { useWindowDimensions } from 'react-native';

/**
 * Тесный экран — короткий по высоте и/или узкий по ширине.
 *
 * Появился после первого device QA на Samsung Galaxy A21s: 6,5 дюйма стекла, но
 * всего 720 физических пикселей в ширину, поэтому Android ставит масштаб 2,25 и
 * в логических единицах остаётся **320 × 712 dp**. Это МЕНЬШЕ, чем у iPhone 12
 * mini (375 × 812), который физически заметно компактнее. На таком экране герои
 * онбординга (маскот 170 dp + заголовок в 36 px) переполняли контейнер, и
 * содержимое рисовалось поверх кнопок — React Native по умолчанию не обрезает
 * то, что вылезло за границы блока.
 *
 * Пороги выбраны так, чтобы отсечь именно дешёвые 720p-телефоны:
 *  - высота 760 dp: A21s даёт 712, iPhone 12 mini 812, современные Android 840+;
 *  - ширина 360 dp: 320 у бюджетных, 360+ у всего остального.
 *
 * Бюджетные Samsung серии A — самый массовый телефон нашего рынка, так что это
 * не экзотика, а основной случай. Но подгонять вёрстку ТОЛЬКО под них нельзя:
 * проверять изменения нужно и на широком экране.
 */
export function useCompactScreen(): {
  /** Мало высоты — уменьшать героев, не центрировать по вертикали. */
  short: boolean;
  /** Мало ширины — следить за переносами и длиной строк. */
  narrow: boolean;
  width: number;
  height: number;
} {
  const { width, height } = useWindowDimensions();
  return { short: height < 760, narrow: width < 360, width, height };
}
